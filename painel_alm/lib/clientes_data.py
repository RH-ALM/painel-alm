def display_options(clientes):
    """Retorna lista de strings 'EMPRESA — nome (CNPJ/CPF)' pra usar num selectbox."""
    return [f"{c['empresa']} — {c['nome']} ({c['cnpj']})" for c in clientes]


def empresa_from_display(display_str):
    return display_str.split(' — ')[0]


def cnpj_from_display(display_str):
    m = re.search(r'\(([\d./-]+)\)\s*$', display_str)
    return m.group(1) if m else None


def find_empresa_by_cnpj(clientes, cnpj):
    digits = re.sub(r'\D', '', cnpj or '')
    for c in clientes:
        if re.sub(r'\D', '', c['cnpj']) == digits:
            return c['empresa']
    return None
